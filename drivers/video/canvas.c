void canvas_present(void) {
    if (!back_buffer) return;
    const fb_info_t* fb = fb_get_info();
    if (fb && fb->address != 0) {
        uint32_t* hw_fb = (uint32_t*)fb->address;
        memcpy(hw_fb, back_buffer, screen_width * screen_height * sizeof(uint32_t));
    }
}
