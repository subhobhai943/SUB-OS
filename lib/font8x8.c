const uint8_t* font8x8_glyph(char c) {
    // Compare as unsigned: `char` is signed here, so a high-bit byte such as a
    // CP437 box-drawing character would otherwise test as negative.
    unsigned char uc = (unsigned char)c;

    // Anything outside the printable range renders as a question mark, which is
    // more legible than a blank when a driver passes raw bytes straight through.
    if (uc < FONT8X8_FIRST || uc > FONT8X8_LAST) uc = '?';
    return font8x8_basic[uc - FONT8X8_FIRST];
}
